"""Pick each plugin's colour from its banner, so the site can wear it.

Run after adding a plugin or changing a banner:  python3 scripts/tints.py
Writes src/content/tints.ts (plugin id -> "r g b"); a missing banner is skipped
and that plugin keeps the default violet.
"""
import colorsys, io, re, urllib.request
from collections import Counter
from PIL import Image

src = open("src/content/registry.ts", encoding="utf-8").read()
pairs = re.findall(r'id: "([^"]+)",(?:(?!\n  \{\n)[\s\S])*?banner: "([^"]+)"', src)

def tint(data: bytes) -> str:
    im = Image.open(io.BytesIO(data)).convert("RGB").resize((96, 48))
    bins, by = Counter(), {}
    for r, g, b in im.getdata():
        h, s, v = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
        if s < 0.45 or v < 0.35:
            continue
        k = int(h * 24) % 24
        bins[k] += s * v  # vivid pixels count more
        by.setdefault(k, []).append(h)
    if not bins:
        return "170 118 222"
    k = bins.most_common(1)[0][0]
    hue = sorted(by[k])[len(by[k]) // 2]
    # Same lightness and saturation for every plugin: only the hue changes.
    r, g, b = colorsys.hls_to_rgb(hue, 0.62, 0.78)
    return f"{round(r * 255)} {round(g * 255)} {round(b * 255)}"

out = {}
for pid, url in pairs:
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "exylia-docs-tints"})
        out[pid] = tint(urllib.request.urlopen(req, timeout=20).read())
    except Exception as e:  # not uploaded yet
        print("skip", pid, e)

body = "\n".join(f'  {pid}: "{rgb}",' for pid, rgb in out.items())
open("src/content/tints.ts", "w").write(
    "/** Generated by scripts/tints.py: each plugin's colour, as rgb channels for `--accent`. */\n"
    f"export const TINTS: Record<string, string> = {{\n{body}\n}};\n"
)
print(len(out), "tints")
